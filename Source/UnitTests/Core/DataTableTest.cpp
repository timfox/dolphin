TEST(DataTable, Formulas)
{
  const Rows data = {
      {"1", "2", "=A1+B1*3"},
      {"0x10", "4.5", "=SUM(A1:B2)"},
      {"=A2/0", "=C1^2", "=AVERAGE(A1:A2)"},
      {"=IF(A1>0,\"pos\",1/0)", "=\"n\"&A1", "=ROUND(2.345,2)"},
      {"=C5", "=B9", "=HEX(255,4)"},
      {"=MAX(A1:B2)-MIN(A1:B2)", "=COUNT(A1:C3)", "=NOPE(1)"},
  };
  EXPECT_EQ(Eval(data, 0, 2), "7");
  EXPECT_EQ(Eval(data, 1, 2), "23.5");
  EXPECT_EQ(Eval(data, 2, 0), "#DIV/0!");
  EXPECT_EQ(Eval(data, 2, 1), "49");
  EXPECT_EQ(Eval(data, 2, 2), "8.5");
  EXPECT_EQ(Eval(data, 3, 0), "pos");
  EXPECT_EQ(Eval(data, 3, 1), "n1");
  EXPECT_EQ(Eval(data, 3, 2), "2.35");
  EXPECT_EQ(Eval(data, 4, 0), "0x00FF");
  EXPECT_EQ(Eval(data, 4, 1), "#REF!");
  EXPECT_EQ(Eval(data, 4, 2), "0x00FF");
  EXPECT_EQ(Eval(data, 5, 0), "15");
  EXPECT_EQ(Eval(data, 5, 1), "8");  // A3 is an error, which COUNT skips
  EXPECT_EQ(Eval(data, 5, 2), "#NAME?");
}

TEST(DataTable, CyclesAndColumnNames)
{
  const Rows data = {{"=B1", "=A1"}, {"10", "=[hp]*2"}};
  EXPECT_EQ(Eval(data, 0, 0), "#CYCLE!");
  EXPECT_EQ(Eval(data, 1, 1, {"hp:u16", "double_hp"}), "20");
  EXPECT_EQ(Eval({{"=[missing]"}}, 0, 0, {"x"}), "#NAME?");
}

TEST(DataTable, LongChainsDontOverflow)
{
  Rows data;
  data.push_back({"1"});
  for (int i = 1; i < 5000; ++i)
    data.push_back({"=A" + std::to_string(i) + "+1"});
  Row header = {"n"};
  Evaluator eval(header, data);
  // Evaluated top to bottom (as the panel and the exporter do), each row only looks one back.
  std::string last;
  for (size_t r = 0; r < data.size(); ++r)
    last = FormatValue(eval.Get(r, 0));
  EXPECT_EQ(last, "5000");
}

TEST(DataTable, ColumnTypes)
{
  const Row header = {"name", "hp", "speed", "flags", "boss", "id:u8"};
  const Rows data = {
      {"Goomba", "1", "0.5", "0x01", "FALSE", "3"},
      {"Koopa", "=B1*2", "1", "0x80000000", "TRUE", "4"},
  };
  const auto columns = DescribeColumns(header, data);
  ASSERT_EQ(columns.size(), 6u);
  EXPECT_EQ(columns[0].type, ColumnType::String);
  EXPECT_EQ(columns[1].type, ColumnType::S32);
  EXPECT_EQ(columns[2].type, ColumnType::F32);
  EXPECT_EQ(columns[3].type, ColumnType::Hex);
  EXPECT_EQ(columns[4].type, ColumnType::Bool);
  EXPECT_EQ(columns[5].type, ColumnType::U8);
  EXPECT_EQ(columns[5].name, "id");
  EXPECT_TRUE(columns[5].explicit_type);
}

TEST(DataTable, ExportCHeader)
{
  const Row header = {"name", "hp", "speed", "flags", "boss", "id:u8"};
  const Rows data = {
      {"Goomba", "1", "0.5", "0x01", "FALSE", "3"},
      {"", "", "", "", "", ""},
      {"Koopa \"Troopa\"", "=B1*2", "1", "0x80000000", "TRUE", "4"},
  };
  const HeaderResult result = ExportCHeader(header, data, "enemies", "data/enemies.csv");
  ASSERT_TRUE(result.ok) << result.error;
  EXPECT_EQ(result.text,
            "// Generated by the Dolphin devkit from data/enemies.csv.\n"
            "// Edit the data table instead: this file is rewritten whenever the table is "
            "saved.\n\n"
            "#pragma once\n\n#include <stdbool.h>\n#include <stdint.h>\n\n"
            "enum enemies_id\n{\n"
            "  ENEMIES_GOOMBA = 0,\n"
            "  ENEMIES_KOOPA__TROOPA_ = 1,\n"
            "};\n\n"
            "typedef struct enemies_row\n{\n"
            "  const char* name;\n"
            "  int32_t hp;\n"
            "  float speed;\n"
            "  uint32_t flags;\n"
            "  bool boss;\n"
            "  uint8_t id;\n"
            "} enemies_row;\n\n"
            "#define ENEMIES_COUNT 2\n\n"
            "static const enemies_row enemies[ENEMIES_COUNT] = {\n"
            "    {\"Goomba\", 1, 0.5f, 0x00000001, false, 3}, // 1\n"
            "    {\"Koopa \\\"Troopa\\\"\", 2, 1.0f, 0x80000000, true, 4}, // 3\n"
            "};\n");
}

TEST(DataTable, ExportCHeaderErrors)
{
  const Row header = {"name", "id:u8"};
  EXPECT_EQ(ExportCHeader(header, {{"a", "300"}}, "t", "t.csv").error,
            "B1 (300) doesn't fit column B (id), which is u8.");
  EXPECT_EQ(ExportCHeader(header, {{"a", "=1/0"}}, "t", "t.csv").error, "B1 is #DIV/0!");
  EXPECT_EQ(ExportCHeader(header, {{"a", "x"}}, "t", "t.csv").error,
            "B1 (\"x\") isn't a number, but column B (id) is u8.");
}

